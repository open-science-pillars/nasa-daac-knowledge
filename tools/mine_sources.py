"""mine_sources: harvest ECCO community issues, cluster recurring
confusions, and draft gotcha candidates for the promotion ladder.

Pulls issues (open and closed) from ECCO-GROUP repos via the GitHub API,
buckets them against a topic lexicon of known-confusable ECCO subjects,
and reports clusters by recurrence. With --draft-dir it writes one
candidate stub per cluster that clears --min-hits, each stub carrying its
evidence links (the issue URLs), generated by the miner's process actor,
status draft, unverified tier. Humans decide what is a real trap; the
miner only counts and cites.

Two buckets route to a register instead of the gotcha ladder, and the
report says so beside the count: can-I-use-X-for-Y questions are
validity-domain candidates, and phrasings of an attempt that failed
(tried, gave up, does not work, proves nothing, workaround, retracted)
are dead-end candidates. A routed bucket's stub carries the register's
concept type and names the register (a tracking issue) where a steward
triages it. The dead-end needles are the same lexicon check_negative.py
runs over local text with --candidates; the selftest keeps the two in
step.

Auth: set GITHUB_TOKEN (unauthenticated API rate limits are low). The
forum (ecco-group.org discussion board) has no API; it is read by hand
against the same lexicon.

Usage:
  mine_sources.py [--repos ECCO-GROUP/ECCOv4-py ECCO-GROUP/ECCO-v4-Python-Tutorial]
      [--min-hits 3] [--draft-dir out/] [--selftest]
"""

